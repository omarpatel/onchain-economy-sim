import assert from "node:assert/strict";
import { describe, it } from "node:test";
import type BN from "bn.js";
import { PublicKey, SystemProgram, type Keypair } from "@solana/web3.js";
import { TOKEN_PROGRAM_ID } from "@solana/spl-token";
import { buildEpochTree, type Allocation } from "../../integration/src/settlement.ts";
import { Chain, PROGRAM_IDS, big, bn, pda, u64le, econ } from "./harness.ts";

const chain = new Chain();
const program = chain.program("dividends");
const PID = PROGRAM_IDS.dividends;
const CLAIM_WINDOW = 3_600n;

const admin = chain.payer;
const mint = chain.createMint(admin.publicKey);
const adminAta = chain.fund(admin.publicKey, mint, econ(1_000_000));
const distributor = pda(PID, "distributor", mint);
const vault = pda(PID, "vault", distributor);
const epochPda = (epoch: bigint) => pda(PID, "epoch", distributor, u64le(epoch));
const receiptPda = (epoch: bigint, claimant: PublicKey) => pda(PID, "receipt", epochPda(epoch), claimant);

const holders: Keypair[] = [chain.wallet(), chain.wallet(), chain.wallet()];
for (const h of holders) chain.createAta(h.publicKey, mint);

interface EpochRoot { epoch: BN; total: BN; claimed: BN; expiresAt: BN; root: number[] }
interface Distributor { epoch: BN; admin: PublicKey }

const setRootIx = (epoch: bigint, root: Uint8Array, total: bigint, signer = admin) =>
  program.methods
    .setEpochRoot(bn(epoch), Array.from(root), bn(total))
    .accountsStrict({
      admin: signer.publicKey,
      distributor,
      epochRoot: epochPda(epoch),
      vault,
      funderAta: chain.ata(signer.publicKey, mint),
      tokenProgram: TOKEN_PROGRAM_ID,
      systemProgram: SystemProgram.programId,
    })
    .instruction();

const claimIx = (epoch: bigint, claimant: Keypair, index: number, amount: bigint, proof: Uint8Array[]) =>
  program.methods
    .claim(bn(index), bn(amount), proof.map((p) => Array.from(p)))
    .accountsStrict({
      claimant: claimant.publicKey,
      distributor,
      epochRoot: epochPda(epoch),
      receipt: receiptPda(epoch, claimant.publicKey),
      vault,
      claimantAta: chain.ata(claimant.publicKey, mint),
      tokenProgram: TOKEN_PROGRAM_ID,
      systemProgram: SystemProgram.programId,
    })
    .instruction();

const closeIx = (epoch: bigint, destination: PublicKey, signer = admin) =>
  program.methods
    .closeEpoch()
    .accountsStrict({
      admin: signer.publicKey,
      distributor,
      epochRoot: epochPda(epoch),
      vault,
      destination,
      tokenProgram: TOKEN_PROGRAM_ID,
    })
    .instruction();

// Epoch 1 allocations, tree built by the production settlement code.
const allocs: Allocation[] = [
  { index: 0, claimant: holders[0].publicKey, amount: econ(100) },
  { index: 1, claimant: holders[1].publicKey, amount: econ(250) },
  { index: 2, claimant: holders[2].publicKey, amount: 7n },
];
const tree1 = buildEpochTree(1n, allocs);

describe("dividends", () => {
  it("initializes a distributor with a program-owned vault", async () => {
    const ix = await program.methods
      .initDistributor(bn(CLAIM_WINDOW))
      .accountsStrict({
        admin: admin.publicKey,
        mint,
        distributor,
        vault,
        tokenProgram: TOKEN_PROGRAM_ID,
        systemProgram: SystemProgram.programId,
      })
      .instruction();
    chain.send([ix]);
    const d = chain.decode<Distributor>(program, "distributor", distributor);
    assert.equal(big(d.epoch), 0n);
    assert.ok(d.admin.equals(admin.publicKey));
    assert.equal(chain.tokenBalance(vault), 0n);
  });

  it("rejects an epoch that is not the next one, and non-admin publishers", async () => {
    assert.ok(chain.fails([await setRootIx(2n, tree1.root, tree1.total)]).has("BadEpoch"));
    const stranger = chain.wallet();
    chain.fund(stranger.publicKey, mint, econ(1));
    assert.ok(chain.fails([await setRootIx(1n, tree1.root, tree1.total, stranger)], [stranger]).has("ConstraintHasOne"));
  });

  it("publishes epoch 1 and funds the vault with the total", async () => {
    chain.send([await setRootIx(1n, tree1.root, tree1.total)]);
    assert.equal(chain.tokenBalance(vault), tree1.total);
    const e = chain.decode<EpochRoot>(program, "epochRoot", epochPda(1n));
    assert.equal(big(e.epoch), 1n);
    assert.equal(big(e.total), tree1.total);
    assert.equal(big(e.claimed), 0n);
    assert.deepEqual(Uint8Array.from(e.root), tree1.root);
    assert.equal(big(e.expiresAt), chain.now() + CLAIM_WINDOW);
  });

  it("pays a valid claim generated by settlement.ts and records a receipt", async () => {
    const a = allocs[0];
    chain.send([await claimIx(1n, holders[0], a.index, a.amount, tree1.proofs[a.index])], [holders[0]]);
    assert.equal(chain.tokenBalance(chain.ata(holders[0].publicKey, mint)), a.amount);
    assert.equal(chain.tokenBalance(vault), tree1.total - a.amount);
    const r = chain.decode<{ amount: BN; index: BN }>(program, "claimReceipt", receiptPda(1n, holders[0].publicKey));
    assert.equal(big(r.amount), a.amount);
    assert.equal(big(r.index), 0n);
    assert.equal(big(chain.decode<EpochRoot>(program, "epochRoot", epochPda(1n)).claimed), a.amount);
  });

  it("rejects a second claim for the same (epoch, claimant)", async () => {
    const a = allocs[0];
    const err = chain.fails([await claimIx(1n, holders[0], a.index, a.amount, tree1.proofs[a.index])], [holders[0]]);
    assert.ok(err.has("already in use"), err.message);
    assert.equal(chain.tokenBalance(chain.ata(holders[0].publicKey, mint)), a.amount);
  });

  it("rejects wrong proofs, inflated amounts and borrowed leaves", async () => {
    const a = allocs[1];
    // someone else's proof
    assert.ok(chain.fails([await claimIx(1n, holders[1], a.index, a.amount, tree1.proofs[2])], [holders[1]]).has("InvalidProof"));
    // right proof, inflated amount
    assert.ok(chain.fails([await claimIx(1n, holders[1], a.index, a.amount + 1n, tree1.proofs[a.index])], [holders[1]]).has("InvalidProof"));
    // holder 2 presenting holder 1's leaf
    assert.ok(chain.fails([await claimIx(1n, holders[2], a.index, a.amount, tree1.proofs[a.index])], [holders[2]]).has("InvalidProof"));
    assert.equal(chain.tokenBalance(chain.ata(holders[1].publicKey, mint)), 0n);
  });

  it("keeps epoch 1 claimable after epoch 2 is published", async () => {
    const allocs2: Allocation[] = [{ index: 0, claimant: holders[2].publicKey, amount: econ(5) }];
    const tree2 = buildEpochTree(2n, allocs2);
    chain.send([await setRootIx(2n, tree2.root, tree2.total)]);
    assert.equal(big(chain.decode<Distributor>(program, "distributor", distributor).epoch), 2n);

    const a = allocs[1];
    chain.send([await claimIx(1n, holders[1], a.index, a.amount, tree1.proofs[a.index])], [holders[1]]);
    assert.equal(chain.tokenBalance(chain.ata(holders[1].publicKey, mint)), a.amount);

    // an epoch-1 proof does not validate against epoch 2
    const stale = allocs[2];
    assert.ok(chain.fails([await claimIx(2n, holders[2], stale.index, stale.amount, tree1.proofs[stale.index])], [holders[2]]).has("InvalidProof"));
    chain.send([await claimIx(2n, holders[2], 0, econ(5), tree2.proofs[0])], [holders[2]]);
    assert.equal(chain.tokenBalance(chain.ata(holders[2].publicKey, mint)), econ(5));
  });

  it("sweeps the unclaimed remainder only after the claim window", async () => {
    assert.ok(chain.fails([await closeIx(1n, adminAta)]).has("EpochNotExpired"));
    const stranger = chain.wallet();
    chain.warp(CLAIM_WINDOW + 1n);
    assert.ok(chain.fails([await closeIx(1n, adminAta, stranger)], [stranger]).has("ConstraintHasOne"));

    const before = chain.tokenBalance(adminAta);
    chain.send([await closeIx(1n, adminAta)]);
    assert.equal(chain.tokenBalance(adminAta), before + 7n); // holder 2 never claimed its 7 units
    assert.equal(chain.account(epochPda(1n)), null);
    // epoch 2 (still within its window, since it was published later) is untouched
    assert.equal(chain.tokenBalance(vault), 0n);
    assert.ok(chain.account(epochPda(2n)));

    // the swept epoch can no longer be claimed
    const late = allocs[2];
    const err = chain.fails([await claimIx(1n, holders[2], late.index, late.amount, tree1.proofs[late.index])], [holders[2]]);
    assert.ok(err.has("AccountNotInitialized"), err.message);
  });

  it("never accepts a root for a past epoch, even after it was swept", async () => {
    // epoch 1 is closed (its account is gone) but the distributor cursor is at 2
    const err = chain.fails([await setRootIx(1n, tree1.root, tree1.total)]);
    assert.ok(err.has("BadEpoch"), err.message);
    assert.equal(chain.account(epochPda(1n)), null);
    // the current epoch cannot be re-published either (its account already exists)
    const allocs2: Allocation[] = [{ index: 0, claimant: holders[0].publicKey, amount: econ(1) }];
    const tree2 = buildEpochTree(2n, allocs2);
    const live = chain.fails([await setRootIx(2n, tree2.root, tree2.total)]);
    assert.ok(live.has("BadEpoch") || live.has("already in use"), live.message);
    assert.notDeepEqual(Uint8Array.from(chain.decode<EpochRoot>(program, "epochRoot", epochPda(2n)).root), tree2.root);
    assert.equal(big(chain.decode<Distributor>(program, "distributor", distributor).epoch), 2n);
  });
});
